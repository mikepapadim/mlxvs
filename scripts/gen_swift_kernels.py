"""Writes swift/Sources/MLXVS/Kernels.swift from the C++ kernel headers, so
that the Swift package runs the same Metal sources. Run after changing
src/kernels.h or src/search_kernels.h; CI checks the file is current."""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADERS = ["src/kernels.h", "src/search_kernels.h"]
STRINGS = ["TOPK_HEADER", "TOPK_SOURCE", "SEARCH_HEADER", "SEARCH_SOURCE", "SEARCH_MC_SOURCE"]


def swift_name(name):
    parts = name.lower().split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def main():
    text = "\n".join((ROOT / h).read_text() for h in HEADERS)
    ints = re.findall(r"constexpr int (\w+) = (\d+);", text)
    out = [
        "// Copyright © 2026 mikepapadim",
        "",
        "// Generated by scripts/gen_swift_kernels.py from src/kernels.h and",
        "// src/search_kernels.h: the Metal sources of the C++ library. Do not edit.",
        "",
        "enum Kernels {",
    ]
    for name, value in ints:
        out.append(f"    static let {swift_name(name)} = {value}")
    for name in STRINGS:
        m = re.search(r"constexpr const char\* " + name + r' = R"\((.*?)\)";', text, re.S)
        if m is None:
            sys.exit(f"{name} not found")
        body = m.group(1)
        if '"""#' in body:
            sys.exit(f"{name} contains a Swift raw string terminator")
        out.append(f'    static let {swift_name(name)} = #"""\n{body}\n"""#')
    out.append("}")
    target = ROOT / "swift/Sources/MLXVS/Kernels.swift"
    new = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        if not target.exists() or target.read_text() != new:
            sys.exit("swift/Sources/MLXVS/Kernels.swift is out of date: run scripts/gen_swift_kernels.py")
        return
    target.write_text(new)


if __name__ == "__main__":
    main()
